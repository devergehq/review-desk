import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'
import { describe, expect, it } from 'vitest'

import type { OutcomeKind } from '../app/types/desk'

/*
 * **`app/types/contract.ts` is generated and not committed, so what needs guarding is the
 * generating.**
 *
 * This file used to regenerate the document and compare it against the committed copy.
 * That check is gone with the copy: there is nothing to disagree with the contract any
 * more, because there is only one file and it is rebuilt from `contract/openapi.yaml` on
 * install and ahead of every `dev`, `build`, `generate`, `typecheck`, `lint` and `test`.
 *
 * What replaces it is the risk that arrangement introduces. A build that generates its own
 * types can fail in a way a committed file cannot: generation can break, and the build can
 * then carry on against whatever was on disk from last time. Silently building the
 * dashboard against a stale contract is worse than committing the file, because at least a
 * committed file shows up in a diff.
 *
 * So: generation fails loudly, and leaves nothing behind to fall back on.
 */

const web = resolve(__dirname, '..')
const SCRIPT = resolve(web, 'scripts/contract-types.mjs')
const OUTPUT = resolve(web, 'app/types/contract.ts')
const CONTRACT = resolve(web, '../contract/openapi.yaml')

/**
 * Run the generator somewhere it cannot find a contract.
 *
 * The script resolves the contract relative to its own location, so a copy of it in a
 * directory with no `../contract/openapi.yaml` beside it *is* the missing-contract case —
 * no environment variable to redirect the path, which would be a way to point a real build
 * at the wrong contract.
 */
function runWhereThereIsNoContract(): { code: number, stderr: string, output: string } {
  const root = mkdtempSync(join(tmpdir(), 'review-desk-contract-'))
  const fakeWeb = join(root, 'web')
  mkdirSync(join(fakeWeb, 'scripts'), { recursive: true })
  mkdirSync(join(fakeWeb, 'app/types'), { recursive: true })
  cpSync(SCRIPT, join(fakeWeb, 'scripts/contract-types.mjs'))

  /*
   * A stale file, put there on purpose. This is the whole point of the test: a previous
   * run's output must not survive a failed one.
   */
  const stale = join(fakeWeb, 'app/types/contract.ts')
  writeFileSync(stale, '// auto-generated by openapi-typescript — from a contract long gone\n')

  try {
    execFileSync('node', [join(fakeWeb, 'scripts/contract-types.mjs')], { encoding: 'utf8' })
    return { code: 0, stderr: '', output: existsSync(stale) ? readFileSync(stale, 'utf8') : '' }
  }
  catch (error) {
    const failure = error as { status?: number, stderr?: string }
    return {
      code: failure.status ?? -1,
      stderr: failure.stderr ?? '',
      output: existsSync(stale) ? readFileSync(stale, 'utf8') : '',
    }
  }
}

describe('generating the contract types', () => {
  it('has happened by the time anything runs', () => {
    /*
     * `pnpm test` generates before it runs vitest, so this file existing is itself the
     * assertion that the wiring works. If this fails, the wiring in `package.json` has
     * come undone and every other test here is running against who knows what.
     */
    expect(
      existsSync(OUTPUT),
      'app/types/contract.ts is missing, so `pnpm test` did not generate it first',
    ).toBe(true)
    expect(readFileSync(OUTPUT, 'utf8')).toContain('auto-generated by openapi-typescript')
  })

  it('fails loudly when the contract is not there', () => {
    const { code, stderr } = runWhereThereIsNoContract()

    expect(code, 'a missing contract must fail the command, not warn').toBeGreaterThan(0)
    expect(stderr).toContain('the contract is not at')
    expect(stderr).toContain('deliberately not committed')
  })

  it('leaves no stale file behind when it fails', () => {
    /*
     * The one that matters. A generator that bails out *after* its output already exists
     * leaves the previous types in place, and the next build succeeds against a contract
     * that has moved — a silent wrong answer rather than a loud failure. The script
     * therefore deletes its output before anything that can fail.
     */
    const { output } = runWhereThereIsNoContract()

    expect(
      output,
      'a failed generation left its previous output on disk, which a later build would use',
    ).toBe('')
  })
})

describe('the contract the generated types come from', () => {
  it('carries every outcome kind the harvester writes', () => {
    /*
     * DEV-862's first drift: `desk.ts` spelled the shapes out by hand and `OutcomeKind`
     * listed seven kinds against the contract's nine. `crates/harvest` records `replied`
     * and `thread_resolved`, and the Inbox's "Author replied" group is built from exactly
     * those rows — so the dashboard rendered values its own types called impossible.
     *
     * `satisfies` makes this a compile-time check as well as a runtime one: if either kind
     * leaves the contract, this file stops type-checking.
     */
    const harvested = ['replied', 'thread_resolved'] satisfies OutcomeKind[]
    expect(harvested).toHaveLength(2)
  })

  it('still declares the schemas the screens import by name', async () => {
    /*
     * `desk.ts` is aliases over the generated module. An alias to a schema that no longer
     * exists is a type error rather than a test failure, so what this checks is the other
     * direction: that the contract still declares the schemas those aliases point at. A
     * schema renamed in `openapi.yaml` would otherwise regenerate perfectly cleanly and
     * break only when something imported it.
     */
    const fresh = astToString(await openapiTS(new URL(`file://${CONTRACT}`)))
    for (const schema of [
      'Inbox',
      'ReviewDetail',
      'DraftDetail',
      'RulesPage',
      'RepoSummary',
      'Rule',
      'Finding',
      'Brief',
      'Draft',
      'DraftLint',
      'Outcome',
      'NitTicket',
      'OutcomeKind',
      'ErrorCode',
      'StartReviewRequest',
      /*
       * DEV-930's three. `PrState` is a new closed set, and the two items are what the
       * posted group and the Reviews list are made of — a schema renamed in the contract
       * would otherwise regenerate cleanly and break only when a page imported it.
       */
      'PrState',
      'InboxPostedItem',
      'ReviewListItem',
    ]) {
      expect(fresh).toContain(`${schema}: `)
    }
  }, 30_000)
})
