//! Embeds the dashboard's static build in the binary, if there is one.
//!
//! `web/.output/public` is the output of `pnpm run generate`, and it is not in the
//! repository — it is a build product of a Node toolchain this crate does not depend on.
//! **So the build has to work both ways.** With the directory present, every file in it
//! becomes an `include_bytes!` in the generated table; with it absent, the table is
//! empty and the server serves a page saying the front end was not built.
//!
//! That is the whole reason this is a build script rather than a dependency on
//! `include_dir`: the condition to express is "embed it if it happens to be there",
//! which a crate that walks a directory at compile time will not do for you, and a
//! `cargo build` that fails on a machine with no Node is not an option DEV-861 allows.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let root = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"))
        .join("../../web/.output/public");

    // Announced whether or not it exists. Cargo re-runs this script when a path it was
    // told about appears, so a front end built after a first `cargo build` is picked up
    // by the next one rather than silently staying unembedded.
    println!("cargo::rerun-if-changed={}", root.display());

    // And the directory above it, because cargo compares modification times and `mv`
    // preserves them. Moving a previously built `public` back into place leaves every
    // mtime inside it untouched, so nothing under `root` would look changed and the
    // binary would keep the empty table — found exactly that way during the hand run for
    // DEV-861. The parent's own mtime does change when a directory appears inside it.
    if let Some(parent) = root.parent() {
        println!("cargo::rerun-if-changed={}", parent.display());
    }

    let mut files = Vec::new();
    if root.is_dir() {
        collect(&root, &root, &mut files);
        files.sort();
    }

    let mut generated = String::from(
        "// Generated by build.rs. The dashboard's static build, or nothing.\n\
         pub static FILES: &[(&str, &[u8])] = &[\n",
    );
    for (route, path) in &files {
        // rerun-if-changed on the directory alone does not notice a file inside it
        // changing, so every file says so for itself.
        println!("cargo::rerun-if-changed={}", path.display());
        writeln!(
            generated,
            "    ({:?}, include_bytes!({:?})),",
            route,
            path.display().to_string()
        )
        .expect("writing to a String cannot fail");
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("embedded.rs");
    std::fs::write(&out, generated).expect("writing the generated asset table");
}

/// Every file under `dir`, as the path it is served at and the path it is read from.
fn collect(root: &Path, dir: &Path, found: &mut Vec<(String, PathBuf)>) {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(_) => return,
    };

    for entry in entries.flatten() {
        let path = entry.path();

        // `file_type()` does not follow the link; `path.is_dir()` would. A symlinked
        // directory under the asset root would otherwise be walked and everything behind
        // it embedded in the binary — `public/etcdir -> /etc` embeds /etc, and
        // `public/secret.txt -> /etc/hosts` becomes servable at `/secret.txt`.
        //
        // Not a security fix, and worth being honest about which it is: planting that
        // link already needs code execution as the developer, because `pnpm run generate`
        // runs the Node toolchain and everything it depends on. It is a build script that
        // should embed the directory it was pointed at and nothing else.
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if kind.is_symlink() {
            continue;
        }

        if kind.is_dir() {
            collect(root, &path, found);
        } else if let Ok(relative) = path.strip_prefix(root) {
            // Served with forward slashes whatever the host separator is: the route is a
            // URL path, not a file path.
            let route = relative
                .components()
                .map(|part| part.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            found.push((route, path));
        }
    }
}
