import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'
import { describe, expect, it } from 'vitest'

import type { OutcomeKind } from '../app/types/desk'

/*
 * **The front end's types cannot drift from the contract without this failing.**
 *
 * DEV-862's first drift was that they already had. `app/types/desk.ts` spelled the shapes
 * out by hand, and `OutcomeKind` listed seven kinds against the contract's nine: the
 * harvester writes `replied` and `thread_resolved`, and the Inbox's "Author replied" group
 * is built from exactly those rows — so the dashboard was rendering values its own types
 * called impossible, and nothing anywhere said so.
 *
 * The fix is not a longer list. It is that there is no list: `app/types/contract.ts` is
 * generated from `contract/openapi.yaml`, `app/types/desk.ts` only gives its schemas short
 * names, and this file regenerates the document and compares. One command puts it right:
 *
 *     pnpm run types:contract
 *
 * Why the file is committed rather than generated at build time. The dashboard is built on
 * a machine that may not have the contract next to it, the generator is a development
 * dependency rather than a build one, and a committed file makes a contract change visible
 * in the pull request's diff as a type change — which is the review this drift needed and
 * did not get.
 */

const COMMITTED = resolve('app/types/contract.ts')
const CONTRACT = resolve('../contract/openapi.yaml')

/** The generator, run the way `pnpm run types:contract` runs it. */
async function generate(): Promise<string> {
  return astToString(await openapiTS(new URL(`file://${CONTRACT}`)))
}

/**
 * The declarations, without the "do not edit this file" banner.
 *
 * The command-line generator writes that banner and the library call does not, so the two
 * differ by it and by nothing else. Stripped here rather than reproduced, because a test
 * that knew the banner's exact wording would fail when the generator changed it. The
 * banner's presence is its own assertion below.
 */
function declarations(source: string): string {
  return source.replace(/^\s*\/\*\*[\s\S]*?\*\/\s*/, '').trimEnd()
}

describe('the generated contract types', () => {
  it('match the contract as it stands', async () => {
    const committed = readFileSync(COMMITTED, 'utf8')
    const fresh = await generate()

    expect(
      declarations(fresh),
      'app/types/contract.ts is not what contract/openapi.yaml generates. '
      + 'Run `pnpm run types:contract` and commit the result.',
    ).toBe(declarations(committed))
  }, 30_000)

  it('are generated, not written', () => {
    expect(readFileSync(COMMITTED, 'utf8')).toContain('auto-generated by openapi-typescript')
  })

  it('carry every outcome kind the harvester writes', () => {
    /*
     * The drift itself, as an assertion a reader can see without diffing a 1700-line
     * generated file. These two are what `crates/harvest` records — a reply on a finding's
     * thread, and that thread being resolved — and they are what the front end could not
     * name. `satisfies` makes this a compile-time check as well as a runtime one: if
     * either kind leaves the contract, this stops type-checking.
     */
    const harvested = ['replied', 'thread_resolved'] satisfies OutcomeKind[]
    expect(harvested).toHaveLength(2)
  })

  it('name the shapes the screens import, so a rename cannot pass silently', async () => {
    /*
     * `desk.ts` is aliases over the generated file. An alias to a schema that no longer
     * exists is a type error rather than a test failure, so what this checks is the other
     * direction: that the contract still declares the schemas those aliases point at. A
     * schema renamed in `openapi.yaml` would otherwise regenerate cleanly and break only
     * when something imported it.
     */
    const fresh = await generate()
    for (const schema of [
      'Inbox',
      'ReviewDetail',
      'DraftDetail',
      'RulesPage',
      'RepoSummary',
      'Rule',
      'Finding',
      'Brief',
      'Draft',
      'DraftLint',
      'Outcome',
      'NitTicket',
      'OutcomeKind',
      'ErrorCode',
      'StartReviewRequest',
    ]) {
      expect(fresh).toContain(`${schema}: `)
    }
  }, 30_000)
})
